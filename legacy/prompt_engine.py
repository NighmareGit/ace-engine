def build_prompt(
    task: Dict[str, Any],
    context: Optional[Dict[str, Any]] = None,
    manifest_path: Optional[str] = None,
) -> str:
    """Build a prompt from a task dict and optional context.

    This is the main entry point for external callers. It handles manifest
    loading, context preparation, and prompt compilation in one call.

    Args:
        task: Task dictionary with at least an 'id' or 'type' key.
        context: Optional context dict with file_tree, relevant_files, project_path, etc.
        manifest_path: Optional path to a PROMPTS_MANIFEST.json. If provided,
            the engine will load it and use manifest-driven compilation.

    Returns:
        A fully rendered prompt string.
    """
    engine = PromptEngine()

    if manifest_path:
        engine.load_manifest(manifest_path)

    context = context or {}
    # Inject the task dict into context for generic fallback
    context.setdefault("task", task)

    task_id = task.get("id", task.get("task_id", "unknown"))
    return engine.compile(task_id, context=context)
