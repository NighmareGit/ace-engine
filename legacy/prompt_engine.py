# ---------------------------------------------------------------------------
# ContextResolver — reads files from disk per context_ref spec
# ---------------------------------------------------------------------------

class ContextResolver:
    """Resolves context references by reading files from disk."""

    def resolve(self, context_refs: List[Dict[str, Any]], base_path: str = "") -> str:
        """Resolve a list of context reference specs into a single text block.

        Each ref is a dict with:
          - path: str   — file path (relative or absolute)
          - type: str   — one of "full_file", "first_50_lines", "pattern_match"
          - pattern: str — (required when type is "pattern_match") regex pattern
        """
        parts: List[str] = []
        for ref in context_refs:
            file_path = ref.get("path", "")
            ref_type = ref.get("type", "full_file")
            pattern = ref.get("pattern", "")

            if not file_path:
                continue

            # Strip leading @ if present (manifest convention)
            file_path = file_path.lstrip("@")

            content = self._read_file(file_path, base_path)
            if content is None:
                parts.append(f"[Could not read: {file_path}]")
                continue

            if ref_type == "full_file":
                lang = file_path.rsplit(".", 1)[-1] if "." in file_path else ""
                parts.append(f"### {file_path}\n```{lang}\n{content}\n```")

            elif ref_type == "first_50_lines":
                lines = content.splitlines(keepends=True)[:50]
                truncated = "".join(lines)
                if len(content.splitlines()) > 50:
                    truncated += f"\n... ({len(content.splitlines()) - 50} more lines)"
                lang = file_path.rsplit(".", 1)[-1] if "." in file_path else ""
                parts.append(f"### {file_path} (first 50 lines)\n```{lang}\n{truncated}\n```")

            elif ref_type == "pattern_match" and pattern:
                matching = self._grep_pattern(content, pattern)
                if matching:
                    parts.append(
                        f"### {file_path} (matching `{pattern}`)\n```\n{matching}\n```"
                    )
                else:
                    parts.append(f"### {file_path} (no matches for `{pattern}`)")

        return "\n\n".join(parts)

    def read_file(self, path: str, base_path: str = "") -> Optional[str]:
        """Public wrapper: read a single file, return content or None."""
        return self._read_file(path, base_path)

    def _read_file(self, path: str, base_path: str = "") -> Optional[str]:
        """Attempt to read a file, trying absolute, then relative to base_path, then cwd.

        Enforces a project boundary (base_path or cwd) to prevent path traversal,
        and limits file reads to MAX_CONTEXT_FILE_SIZE.
        """
        candidates = [Path(path)]
        if base_path:
            candidates.append(Path(base_path) / path)
        candidates.append(Path.cwd() / path)

        # Determine the allowed root directory for path traversal guard
        root = Path(base_path).resolve() if base_path else Path.cwd().resolve()

        for p in candidates:
            try:
                resolved = p.resolve()
                # Path traversal check: resolved path must be within project root
                try:
                    resolved.relative_to(root)
                except ValueError:
                    logger.warning(
                        "BLOCKED path traversal: %s escapes project root %s",
                        path,
                        root,
                    )
                    continue

                if p.is_file():
                    file_size = p.stat().st_size
                    if file_size > MAX_CONTEXT_FILE_SIZE:
                        # Return truncated version: first 50 lines + size warning
                        lines: List[str] = []
                        with open(p, "r", encoding="utf-8") as fh:
                            for i, line in enumerate(fh):
                                if i >= 50:
                                    break
                                lines.append(line)
                        return (
                            "".join(lines)
                            + f"\n... [File truncated: {file_size} bytes exceeds "
                            f"{MAX_CONTEXT_FILE_SIZE // 1024}KB limit]"
                        )
                    return p.read_text(encoding="utf-8")
            except (OSError, UnicodeDecodeError):
                continue
        return None

    @staticmethod
    def _grep_pattern(content: str, pattern: str) -> str:
        """Return lines matching a regex pattern, with ReDoS protection."""
        # Reject patterns with nested quantifiers (ReDoS risk)
        if _NESTED_QUANTIFIER_RE.search(pattern):
            raise ValueError(
                f"Regex pattern rejected (nested quantifiers / ReDoS risk): {pattern}"
            )

        compiled = re.compile(pattern)
        matched_lines: List[str] = []
        lines = content.splitlines()

        def _do_search() -> None:
            for i, line in enumerate(lines, start=1):
                if compiled.search(line):
                    matched_lines.append(f"{i:>5}: {line}")
                if len(matched_lines) > 1000:
                    break

        # Use signal.alarm on Unix main thread for a 5-second hard timeout
        if (
            hasattr(signal, "alarm")
            and threading.current_thread() is threading.main_thread()
        ):
            def _timeout_handler(signum: int, frame: Any) -> None:
                raise TimeoutError("Regex search timed out after 5 seconds")

            old_handler = signal.signal(signal.SIGALRM, _timeout_handler)
            signal.alarm(5)
            try:
                _do_search()
            except TimeoutError:
                matched_lines.append(
                    "... [Regex search timed out — pattern may be too complex]"
                )
            finally:
                signal.alarm(0)
                signal.signal(signal.SIGALRM, old_handler)
        else:
            _do_search()

        # Hard cap on matched lines
        if len(matched_lines) > 1000:
            matched_lines = matched_lines[:1000]
            matched_lines.append("... [Truncated: >1000 matching lines]")

        return "\n".join(matched_lines)


# ---------------------------------------------------------------------------
# RailsApplier — applies constraint rails from manifest
# ---------------------------------------------------------------------------

class RailsApplier:
    """Applies constraint rails defined in a manifest to prompt context."""

    def __init__(self, rails: Optional[Dict[str, Any]] = None):
        self.rails: Dict[str, Any] = rails or {}

    def apply(
        self,
        context_text: str,
        template: str,
        extra_checklist: List[str],
    ) -> Tuple[str, str, List[str]]:
        """Apply rails to the context and template.

        Returns (context_text, template, extra_checklist) after applying rails.
        """
        # 1. Truncate context if max_context_tokens is set
        max_tokens = self.rails.get("max_context_tokens", DEFAULT_MAX_CONTEXT_TOKENS)
        if max_tokens:
            context_text = self._truncate_to_tokens(context_text, max_tokens)

        # 2. Build additional checklist items from rails
        if self.rails.get("require_type_hints"):
            extra_checklist.append("- [ ] All functions have proper type annotations")

        if self.rails.get("require_docstrings"):
            extra_checklist.append("- [ ] All public functions/classes have docstrings")

        # 3. Add test generation instructions if required
        if self.rails.get("require_tests"):
            test_instruction = (
                "\n## Test Generation\n"
                "Generate comprehensive unit tests for all new or changed code. "
                "Tests should cover happy paths, edge cases, and error conditions.\n"
            )
            if "## Verification Checklist" in template:
                template = template.replace(
                    "## Verification Checklist",
                    test_instruction + "\n## Verification Checklist",
                )
            else:
                template += test_instruction

        return context_text, template, extra_checklist

    def _truncate_to_tokens(self, text: str, max_tokens: int) -> str:
        """Truncate text to approximate token limit."""
        max_chars = max_tokens * CHARS_PER_TOKEN
        if len(text) <= max_chars:
            return text
        truncated = text[:max_chars]
        # Try to truncate at a clean boundary
        last_newline = truncated.rfind("\n")
        if last_newline > max_chars * 0.9:
            truncated = truncated[:last_newline]
        return truncated + "\n\n[Context truncated to fit token limit]"


# ---------------------------------------------------------------------------
# PromptEngine — main prompt compilation engine
# ---------------------------------------------------------------------------

class PromptEngine:
    """Manifest-driven prompt engine that builds complete prompts for tasks.

    Usage::

        engine = PromptEngine()
        engine.load_manifest("PROMPTS_MANIFEST.json")
        prompt = engine.compile("T01", context=my_context_dict)
    """

    def __init__(self) -> None:
        self.manifest: Optional[Dict[str, Any]] = None
        self.manifest_path: Optional[str] = None
        self._context_resolver = ContextResolver()
        self._rails_applier: Optional[RailsApplier] = None

    def load_manifest(self, path: str) -> None:
        """Load a PROMPTS_MANIFEST.json file."""
        p = Path(path)
        if not p.is_file():
            raise FileNotFoundError(f"Manifest not found: {path}")

        with open(p, "r", encoding="utf-8") as fh:
            self.manifest = json.load(fh)

        self.manifest_path = str(p.resolve())

        # Initialize rails applier from global manifest rails if present
        rails_cfg = self.manifest.get("rails", {})
        self._rails_applier = RailsApplier(rails=rails_cfg)

    def compile(self, task_id: str, context: Optional[Dict[str, Any]] = None) -> str:
        """Build a complete prompt for the given task_id.

        If the task exists in the loaded manifest, uses its spec and template.
        Otherwise falls back to a generic prompt built from the task dict
        in context (backward compatible).
        """
        context = context or {}

        # Check if task is in manifest
        if self.manifest and task_id in self.manifest.get("tasks", {}):
            return self._compile_from_manifest(task_id, context)

        # Fall back to generic prompt
        return self._compile_generic(task_id, context)

    def _compile_from_manifest(self, task_id: str, context: Dict[str, Any]) -> str:
        """Compile a prompt using the manifest spec for the given task."""
        task_spec = self.manifest["tasks"][task_id]  # type: ignore[index]

        task_type = task_spec.get("task_type", "implement")
        template = self._select_template(task_type, task_spec)

        # SECURITY: Block system prompt override — system prompts must never
        # be replaceable from manifest data.
        overrides = task_spec.get("template_overrides", {})
        if overrides.get("system_prompt_override"):
            logger.warning(
                "BLOCKED system_prompt_override in task %s — "
                "system prompts must not be overridable from manifests.",
                task_id,
            )

        # SECURITY: Prepend anti-injection instruction to template
        template = _USER_DATA_INSTRUCTION + template

        # Build placeholder values from spec
        placeholders = self._build_placeholders(task_spec, context)

        # Resolve context references (file reads)
        context_refs = task_spec.get("context_refs", [])
        base_path = context.get("project_path", "")
        context_text = self._context_resolver.resolve(context_refs, base_path)

        # Apply per-task rails (manifest task rails override global)
        task_rails = task_spec.get("rails")
        if task_rails:
            applier = RailsApplier(rails=task_rails)
        elif self._rails_applier:
            applier = self._rails_applier
        else:
            applier = RailsApplier()

        extra_checklist: List[str] = []
        context_text, template, extra_checklist = applier.apply(
            context_text, template, extra_checklist
        )

        # SECURITY: Pre-truncate context if estimated total would exceed budget
        estimated_total = (
            len(template)
            + len(context_text)
            + sum(len(str(v)) for v in placeholders.values())
        )
        if estimated_total > MAX_TOTAL_PROMPT_CHARS:
            excess = estimated_total - MAX_TOTAL_PROMPT_CHARS
            if len(context_text) > excess:
                context_text = context_text[: len(context_text) - excess]
                context_text += "\n\n[Context truncated to fit prompt size limit]"
            else:
                context_text = "[Context removed to fit prompt size limit]"

        # Render template with placeholders
        rendered = self._render(template, placeholders)

        # Replace the {{relevant_files}} placeholder with resolved context
        rendered = rendered.replace("{{relevant_files}}", context_text)

        # Inject extra checklist items
        if extra_checklist:
            rendered = self._append_checklist(rendered, extra_checklist)

        # Inject extra sections from template_overrides (skip system_prompt_override)
        for section in overrides.get("extra_sections", []):
            content = section.get("content", "")
            if content:
                rendered += f"\n\n{content}"

        # SECURITY: Final hard cap on total prompt size
        if len(rendered) > MAX_TOTAL_PROMPT_CHARS:
            rendered = (
                rendered[:MAX_TOTAL_PROMPT_CHARS]
                + "\n\n[Prompt truncated to fit size limit]"
            )

        return rendered

    def _compile_generic(self, task_id: str, context: Dict[str, Any]) -> str:
        """Build a generic prompt — backward compatible with old CodeGenerator behavior."""
        task = context.get("task", {})
        task_type = task.get("type", task.get("task_type", "implement"))

        template = TASK_TYPE_TEMPLATES.get(task_type, IMPLEMENT_TEMPLATE)

        # Build placeholders from task dict
        goal = task.get("goal", task.get("description", f"Complete task: {task_id}"))
        constraints_list = task.get("constraints", [])
        success_list = task.get("success_criteria", task.get("acceptance_criteria", []))
        arch_notes = task.get("architecture_notes", "")
        imports_list = task.get("imports", [])
        acceptance = task.get("acceptance_criteria", [])

        file_tree = context.get("file_tree", "")
        relevant_files = context.get("relevant_files", "")

        # SECURITY: Sanitize and wrap user-controlled fields in <user_data> tags
        def _sanitize(value: str) -> str:
            """Strip template markers from user data to prevent injection."""
            return str(value).replace("{{", "").replace("}}", "")

        def _wrap(field_name: str, raw: str) -> str:
            """Wrap sanitized user-controlled value in <user_data> XML."""
            return f'<user_data field="{field_name}">{_sanitize(raw)}</user_data>'

        placeholders = {
            "goal": _wrap("goal", goal),
            "description": _sanitize(task.get("description", "")),
            "constraints": _wrap("constraints", self._as_bullet_list(constraints_list) if constraints_list else "(none)"),
            "success_criteria": _wrap("success_criteria", self._as_bullet_list(success_list) if success_list else "(none specified)"),
            "architecture_notes": _wrap("architecture_notes", arch_notes or "(none specified)"),
            "file_tree": file_tree or "(no project tree available)",
            "relevant_files": relevant_files or "(no relevant files loaded)",
            "imports": self._as_bullet_list(imports_list) if imports_list else "(none specified)",
            "task_type": task_type,
            "title": task.get("title", task_id),
            "acceptance_criteria": self._format_checklist(acceptance),
        }

        # SECURITY: Prepend anti-injection instruction
        template = _USER_DATA_INSTRUCTION + template
        rendered = self._render(template, placeholders)
        return rendered

    # ------------------------------------------------------------------
    # Template helpers
    # ------------------------------------------------------------------

    def _select_template(self, task_type: str, task_spec: Dict[str, Any]) -> str:
        """Select template based on task_type, with override from spec."""
        # Allow manifest to override template entirely
        if "template" in task_spec:
            return task_spec["template"]
        return TASK_TYPE_TEMPLATES.get(task_type, IMPLEMENT_TEMPLATE)

    @staticmethod
    def _sanitize_user_data(value: str) -> str:
        """Strip {{ and }} patterns from user-controlled values to prevent injection."""
        return str(value).replace("{{", "").replace("}}", "")

    def _build_placeholders(
        self, task_spec: Dict[str, Any], context: Dict[str, Any]
    ) -> Dict[str, str]:
        """Build a dict of placeholder name → rendered value from spec + context.

        User-controlled fields (goal, architecture_notes, constraints,
        success_criteria) are wrapped in <user_data> XML delimiters to
        prevent indirect prompt injection.
        """
        # Navigate nested spec if present
        spec = task_spec.get("spec", task_spec)

        goal = spec.get("goal", task_spec.get("goal", ""))
        constraints = spec.get("constraints", task_spec.get("constraints", []))
        success_criteria = spec.get("success_criteria", task_spec.get("success_criteria", []))
        arch_notes = spec.get("architecture_notes", task_spec.get("architecture_notes", ""))
        imports_list = task_spec.get("imports_from_project", [])
        title = task_spec.get("title", "")
        task_type = task_spec.get("task_type", "implement")

        # Acceptance criteria from spec or top-level
        acceptance = spec.get("success_criteria", task_spec.get("acceptance_criteria", []))

        # File tree from context
        file_tree = context.get("file_tree", "")
        if not file_tree:
            tree = context.get("project_tree") or context.get("project_structure")
            if tree:
                file_tree = self._render_tree(tree)

        imports_text = self._as_bullet_list(imports_list) if imports_list else "(none specified)"

        def _wrap(field_name: str, raw: str) -> str:
            """Wrap sanitized user-controlled value in <user_data> XML."""
            sanitized = self._sanitize_user_data(raw)
            return f'<user_data field="{field_name}">{sanitized}</user_data>'

        # Build raw values, then wrap user-controlled fields
        goal_raw = goal or "(no goal specified)"
        if isinstance(goal_raw, list):
            goal_raw = self._as_bullet_list(goal_raw)
        goal_text = _wrap("goal", str(goal_raw))

        constraints_raw = self._as_bullet_list(constraints) if constraints else "(none)"
        constraints_text = _wrap("constraints", str(constraints_raw))

        success_raw = self._as_bullet_list(success_criteria) if success_criteria else "(none specified)"
        success_text = _wrap("success_criteria", str(success_raw))

        arch_raw = arch_notes or "(none specified)"
        arch_text = _wrap("architecture_notes", str(arch_raw))

        return {
            "goal": goal_text,
            "description": self._sanitize_user_data(task_spec.get("description", "")),
            "constraints": constraints_text,
            "success_criteria": success_text,
            "architecture_notes": arch_text,
            "file_tree": file_tree or "(no project tree available)",
            "relevant_files": "",  # Filled later from context resolution
            "imports": imports_text,
            "task_type": task_type,
            "title": title or "(untitled task)",
            "acceptance_criteria": self._format_checklist(acceptance),
        }

    @staticmethod
    def _render(template: str, placeholders: Dict[str, str]) -> str:
        """Replace all {{key}} placeholders in template in a single pass.

        Uses re.sub with a callback to prevent nested expansion — each
        placeholder is resolved exactly once, and only known keys are replaced.
        """
        def _replace(match: re.Match) -> str:
            key = match.group(1)
            return str(placeholders.get(key, match.group(0)))

        return re.sub(r'\{\{(\w+)\}\}', _replace, template)

    @staticmethod
    def _as_bullet_list(items: Any) -> str:
        """Convert a list of strings to a bullet list."""
        if isinstance(items, str):
            return items
        if isinstance(items, list):
            return "\n".join(f"- {item}" for item in items)
        return str(items)

    @staticmethod
    def _format_checklist(items: Any) -> str:
        """Format acceptance criteria as a checklist block."""
        if isinstance(items, str):
            return items
        if isinstance(items, list):
            return "\n".join(f"- [ ] {item}" for item in items)
        return ""

    @staticmethod
    def _render_tree(tree: Any, indent: int = 0) -> str:
        """Render a project tree (dict, list, or string)."""
        if isinstance(tree, str):
            return tree
        if isinstance(tree, dict):
            lines: List[str] = []
            for key, value in tree.items():
                prefix = "  " * indent
                if isinstance(value, dict):
                    lines.append(f"{prefix}{key}/")
                    lines.append(PromptEngine._render_tree(value, indent + 1))
                elif isinstance(value, (int, float)):
                    lines.append(f"{prefix}{key}  ({value} bytes)")
                else:
                    lines.append(f"{prefix}{key}")
            return "\n".join(lines)
        if isinstance(tree, list):
            return "\n".join("  " * indent + str(item) for item in tree)
        return str(tree)

    @staticmethod
    def _append_checklist(rendered: str, extra_items: List[str]) -> str:
        """Append extra checklist items to the Verification Checklist section."""
        if not extra_items:
            return rendered

        extra_block = "\n".join(extra_items)
        marker = "## Verification Checklist"

        if marker in rendered:
            parts = rendered.split(marker, 1)
            checklist_content = parts[1]
            # Find where the checklist content ends
            next_section = checklist_content.find("\n## ")
            if next_section != -1:
                before = checklist_content[:next_section]
                after = checklist_content[next_section:]
                new_checklist = before + "\n" + extra_block + after
            else:
                new_checklist = checklist_content + "\n" + extra_block
            return parts[0] + marker + new_checklist

        return rendered + "\n\n" + extra_block


